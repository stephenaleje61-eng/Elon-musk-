// Function to find the most contextually relevant Elon reply
export function getSmartElonReply(userMessage: string, userName: string): string {
  const lower = userMessage.toLowerCase();

  // Check topic matches
  for (const topic of ELON_TOPIC_REPLIES) {
    if (topic.keywords.some((k) => lower.includes(k))) {
      const idx = Math.floor(Math.random() * topic.replies.length);
      let reply = topic.replies[idx];
      if (Math.random() > 0.6) {
        reply = `@${userName} ${reply}`;
      }
      return reply;
    }
  }

  // Random general reply
  const randomIdx = Math.floor(Math.random() * GENERAL_ELON_REPLIES.length);
  const generalReply = GENERAL_ELON_REPLIES[randomIdx];
  return Math.random() > 0.5 ? `@${userName} ${generalReply}` : generalReply;
}
